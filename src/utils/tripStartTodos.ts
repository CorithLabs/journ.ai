import type { TodoItem, TravelMode } from '../db';
import { travelBookingTitle } from './travel';
import { needsTicket } from './travelSuggest';

const TICKETS: Partial<Record<TravelMode, string>> = {
  flight: 'flight tickets',
  train: 'train tickets',
  bus: 'bus tickets',
  ferry: 'ferry tickets',
};

/** Same wording as the to-dos made after the intake, so the two never duplicate. */
export const BOOK_STAY = 'Book accommodation for each night';
export const SAVE_STAY = 'Save your hotel booking';

export function saveTicketsTitle(mode: TravelMode): string {
  return `Save your ${TICKETS[mode] ?? 'tickets'}`;
}

type NewTodo = Omit<TodoItem, 'id' | 'createdAt' | 'updatedAt'>;

/**
 * What Essentials should hold for a new trip, from what was said when making
 * it:
 *   tickets not booked → "Book flights to Tokyo"   (the booking to make)
 *   tickets booked     → "Save your flight tickets" (somewhere to put them)
 *   stay not booked, or not answered → "Book accommodation for each night"
 *   stay booked        → "Save your hotel booking"
 * A road trip has no ticket, so nothing about one.
 *
 * "Save your …" tasks are finished with Attach proof, which files the ticket
 * under Saved and ticks the task.
 */
export function tripStartTodos(
  planId: string,
  { mode, destination, ticketsBooked, stayBooked }: {
    mode?: TravelMode;
    destination: string;
    ticketsBooked: boolean;
    stayBooked: boolean | null;
  },
): NewTodo[] {
  const base = { planId, status: 'todo' as const, autoGenerated: true };
  const out: NewTodo[] = [];
  if (mode && needsTicket(mode)) {
    out.push(
      ticketsBooked
        ? { ...base, title: saveTicketsTitle(mode), category: 'Document' }
        : { ...base, title: travelBookingTitle(mode, destination)!, category: 'Booking' },
    );
  }
  out.push(
    stayBooked
      ? { ...base, title: SAVE_STAY, category: 'Document' }
      : { ...base, title: BOOK_STAY, category: 'Booking' },
  );
  return out;
}
