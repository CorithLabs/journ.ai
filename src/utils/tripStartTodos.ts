import type { TodoItem, TravelMode } from '../db';
import { travelBookingTitle } from './travel';
import { needsTicket } from './travelSuggest';
import { countryFacts, plugLabel, plugsFit } from '../data/countryFacts';

const TICKETS: Partial<Record<TravelMode, string>> = {
  flight: 'flight tickets',
  train: 'train tickets',
  bus: 'bus tickets',
  ferry: 'ferry tickets',
};

/** Same wording as the to-dos made after the intake, so the two never duplicate. */
export const BOOK_STAY = 'Book accommodation for each night';
export const SAVE_STAY = 'Save your hotel booking';

export function saveTicketsTitle(mode: TravelMode): string {
  return `Save your ${TICKETS[mode] ?? 'tickets'}`;
}

type NewTodo = Omit<TodoItem, 'id' | 'createdAt' | 'updatedAt'>;

/*
 * The things people forget, as packing to-dos. The plug adapter and the eSIM
 * are for another country, so they are left off a trip known to stay in one;
 * an unknown trip gets them, since forgetting one abroad costs more than
 * ticking off one that was not needed.
 */
const ADAPTER = 'Pack a universal plug adapter';
const BASICS: { title: string; abroadOnly: boolean }[] = [
  { title: ADAPTER, abroadOnly: true },
  { title: 'Set up an eSIM for data', abroadOnly: true },
  { title: 'Pack headache medicine', abroadOnly: false },
  { title: 'Charge and pack a power bank', abroadOnly: false },
];

/**
 * Travel basics for a trip; `international` false leaves out the abroad-only
 * ones. Knowing the countries makes the adapter specific — "Type G (United
 * Kingdom, 230 V)" — and drops it when the plugs from home already fit.
 */
export function travelBasics(
  planId: string,
  international: boolean | null | undefined,
  countries: { destination?: string | null; origin?: string | null } = {},
): NewTodo[] {
  const away = countryFacts(countries.destination);
  const home = countryFacts(countries.origin);
  return BASICS
    .filter((b) => !(b.abroadOnly && international === false))
    .flatMap((b) => {
      if (b.title !== ADAPTER || !away) return [b.title];
      if (home && home.code !== away.code && plugsFit(home, away)) return [];
      if (home && home.code === away.code) return [];
      return [`Pack a plug adapter for ${plugLabel(away.plugs)} (${away.name}, ${away.voltage})`];
    })
    .map((title) => ({ planId, title, category: 'Packing' as const, status: 'todo' as const, autoGenerated: true }));
}

/**
 * What Essentials should hold for a new trip, from what was said when making
 * it:
 *   tickets not booked → "Book flights to Tokyo"   (the booking to make)
 *   tickets booked     → "Save your flight tickets" (somewhere to put them)
 *   stay not booked, or not answered → "Book accommodation for each night"
 *   stay booked        → "Save your hotel booking"
 * A road trip has no ticket, so nothing about one.
 *
 * "Save your …" tasks are finished with Attach proof, which files the ticket
 * under Saved and ticks the task.
 */
export function tripStartTodos(
  planId: string,
  { mode, destination, ticketsBooked, stayBooked, international, countries }: {
    mode?: TravelMode;
    destination: string;
    ticketsBooked: boolean;
    stayBooked: boolean | null;
    international?: boolean | null;
    countries?: { destination?: string | null; origin?: string | null };
  },
): NewTodo[] {
  const base = { planId, status: 'todo' as const, autoGenerated: true };
  const out: NewTodo[] = [];
  if (mode && needsTicket(mode)) {
    out.push(
      ticketsBooked
        ? { ...base, title: saveTicketsTitle(mode), category: 'Document' }
        : { ...base, title: travelBookingTitle(mode, destination)!, category: 'Booking' },
    );
  }
  out.push(
    stayBooked
      ? { ...base, title: SAVE_STAY, category: 'Document' }
      : { ...base, title: BOOK_STAY, category: 'Booking' },
  );
  return [...out, ...travelBasics(planId, international, countries)];
}
