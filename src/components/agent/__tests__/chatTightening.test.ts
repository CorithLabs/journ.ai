import { describe, it, expect, vi, beforeEach } from 'vitest';
import { executeAgentAction, buildSystemPrompt } from '../agentActions';
import { activityRef } from '../planOps';
import { db, type Activity, type Plan } from '../../../db';

const act = (id: string, name: string, time: string): Activity => ({
  id, name, time, locationName: '', notes: '', pinnedToTodo: false,
});

const plan = (): Plan => ({
  id: 'p1', name: 'Tokyo', destination: 'Tokyo, Japan', startDate: '2026-11-09', endDate: '2026-11-11',
  createdAt: '', updatedAt: '', deleted: false,
  itinerary: [
    { dayIndex: 0, label: 'Day 1 — Mon 9 Nov', activities: [act('temple-1', 'Senso-ji Temple', 'morning'), act('lunch-1', 'Ramen lunch', 'noon')] },
    { dayIndex: 1, label: 'Day 2 — Tue 10 Nov', activities: [act('market-1', 'Tsukiji Market', 'morning'), act('museum-1', 'Mori Art Museum', 'noon')] },
    { dayIndex: 2, label: 'Day 3 — Wed 11 Nov', activities: [] },
  ],
});

const saved = () => vi.mocked(db.plans.update).mock.calls.at(-1)![1] as Partial<Plan>;
const day = (p: Partial<Plan>, i: number) => p.itinerary!.find((d) => d.dayIndex === i)!.activities;

beforeEach(() => {
  vi.clearAllMocks();
  vi.mocked(db.plans.update).mockResolvedValue(1);
  vi.mocked(db.todos.toArray).mockResolvedValue([]);
  vi.mocked(db.clipboard.toArray).mockResolvedValue([]);
});

// "Swap X on day 1 with Y on day 2" — each takes the other's place.
describe('swapping', () => {
  it('trades the day, part of the day and place of two activities', async () => {
    const res = await executeAgentAction(plan(), {
      name: 'swap_activities',
      args: { refA: activityRef({ id: 'lunch-1' }), refB: activityRef({ id: 'market-1' }) },
    });
    expect(res.ok).toBe(true);
    const p = saved();
    expect(day(p, 0).map((a) => [a.name, a.time])).toEqual([['Senso-ji Temple', 'morning'], ['Tsukiji Market', 'noon']]);
    expect(day(p, 1).map((a) => [a.name, a.time])).toEqual([['Ramen lunch', 'morning'], ['Mori Art Museum', 'noon']]);
    expect(res.message).toMatch(/Ramen lunch" is now on Day 2/);
  });

  it('works by name and day too', async () => {
    const res = await executeAgentAction(plan(), {
      name: 'swap_activities',
      args: { nameA: 'temple', dayA: 0, nameB: 'museum', dayB: 1 },
    });
    expect(res.ok).toBe(true);
    expect(day(saved(), 1).map((a) => a.name)).toContain('Senso-ji Temple');
  });

  it('moves saved items filed under each with it', async () => {
    vi.mocked(db.clipboard.toArray).mockResolvedValue([
      { id: 'c1', planId: 'p1', type: 'Other', title: 'Market tour ticket', linkedDayIndex: 1, linkedActivityId: 'market-1', createdAt: '', updatedAt: '' },
    ]);
    await executeAgentAction(plan(), { name: 'swap_activities', args: { nameA: 'ramen', nameB: 'tsukiji' } });
    expect(db.clipboard.update).toHaveBeenCalledWith('c1', expect.objectContaining({ linkedDayIndex: 0 }));
  });
});

describe('not creating duplicates', () => {
  it('refuses to add an activity already in the trip, and says where it is', async () => {
    const res = await executeAgentAction(plan(), { name: 'add_activity', args: { dayIndex: 2, name: 'senso-ji temple', time: 'morning' } });
    expect(res.ok).toBe(false);
    expect(res.message).toMatch(/already on Day 1/);
    expect(db.plans.update).not.toHaveBeenCalled();
  });

  it('allows a genuine repeat when asked', async () => {
    const res = await executeAgentAction(plan(), { name: 'add_activity', args: { dayIndex: 2, name: 'Ramen lunch', time: 'noon', allowRepeat: true } });
    expect(res.ok).toBe(true);
  });

  it('refuses a to-do that already exists, done or not', async () => {
    vi.mocked(db.todos.toArray).mockResolvedValue([
      { id: 't1', planId: 'p1', title: 'Book the Shinkansen', category: 'Booking', status: 'done', autoGenerated: false, createdAt: '', updatedAt: '' },
    ]);
    const res = await executeAgentAction(plan(), { name: 'add_todo', args: { title: 'book the shinkansen' } });
    expect(res.ok).toBe(false);
    expect(res.message).toMatch(/already on your to-do list, ticked off/);
    expect(db.todos.add).not.toHaveBeenCalled();
  });

  it('will not rename an activity into a copy of another', async () => {
    const res = await executeAgentAction(plan(), { name: 'edit_activity', args: { nameMatch: 'ramen', newName: 'Tsukiji Market' } });
    expect(res.ok).toBe(false);
  });
});

// "Add X in the morning" goes in the morning, not to the end of the day.
describe('parts of the day', () => {
  it('adds a morning activity among the morning', async () => {
    const res = await executeAgentAction(plan(), { name: 'add_activity', args: { dayIndex: 0, name: 'Asakusa walk', time: 'morning' } });
    expect(res.message).toMatch(/Day 1, Morning/);
    expect(day(saved(), 0).map((a) => a.name)).toEqual(['Senso-ji Temple', 'Asakusa walk', 'Ramen lunch']);
  });

  it('puts it first when asked', async () => {
    await executeAgentAction(plan(), { name: 'add_activity', args: { dayIndex: 0, name: 'Coffee', time: 'morning', position: 'first' } });
    expect(day(saved(), 0)[0].name).toBe('Coffee');
  });

  it('places a fixed time in its part of the day', async () => {
    const res = await executeAgentAction(plan(), { name: 'add_activity', args: { dayIndex: 1, name: 'Robot show', time: '7pm' } });
    expect(res.message).toMatch(/Evening · 7:00 PM/);
    expect(day(saved(), 1).at(-1)!.time).toBe('19:00');
  });

  it('moves an activity up its day', async () => {
    await executeAgentAction(plan(), { name: 'move_activity', args: { nameMatch: 'museum', position: 'first', time: 'morning' } });
    expect(day(saved(), 1).map((a) => a.name)).toEqual(['Mori Art Museum', 'Tsukiji Market']);
  });

  it('moves one after another on a different day', async () => {
    await executeAgentAction(plan(), { name: 'move_activity', args: { nameMatch: 'ramen', toDayIndex: 1, after: activityRef({ id: 'market-1' }) } });
    expect(day(saved(), 1).map((a) => a.name)).toEqual(['Tsukiji Market', 'Ramen lunch', 'Mori Art Museum']);
    expect(day(saved(), 1)[1].time).toBe('morning');
  });

  it('refuses a time it cannot read', async () => {
    const res = await executeAgentAction(plan(), { name: 'edit_activity', args: { nameMatch: 'ramen', time: 'whenever' } });
    expect(res.ok).toBe(false);
  });
});

describe('telling activities apart', () => {
  it('lists the candidates with their refs when a name fits more than one', async () => {
    const p = plan();
    p.itinerary[2].activities = [act('museum-2', 'Edo Museum', 'noon')];
    const res = await executeAgentAction(p, { name: 'remove_activity', args: { nameMatch: 'museum' } });
    expect(res.ok).toBe(false);
    expect(res.message).toContain(activityRef({ id: 'museum-1' }));
    expect(res.message).toContain(activityRef({ id: 'museum-2' }));
    expect(db.plans.update).not.toHaveBeenCalled();
  });
});

describe('the tools that were missing', () => {
  it('themes a day, keeping its number', async () => {
    await executeAgentAction(plan(), { name: 'rename_day', args: { dayIndex: 1, theme: 'Markets and art' } });
    expect(saved().itinerary![1].label).toBe('Day 2 — Markets and art');
  });

  it('adds days when the trip gets longer', async () => {
    const res = await executeAgentAction(plan(), { name: 'set_trip_dates', args: { endDate: '2026-11-12' } });
    expect(res.ok).toBe(true);
    expect(saved()).toMatchObject({ endDate: '2026-11-12' });
    expect(saved().itinerary).toHaveLength(4);
  });

  it('asks before dates remove days that have activities', async () => {
    const res = await executeAgentAction(plan(), { name: 'set_trip_dates', args: { endDate: '2026-11-09' } });
    expect(res.ok).toBe(false);
    expect(res.message).toMatch(/remove Day 2, with 2 stops/);
    expect(db.plans.update).not.toHaveBeenCalled();
    const ok = await executeAgentAction(plan(), { name: 'set_trip_dates', args: { endDate: '2026-11-09', confirmRemoval: true } });
    expect(ok.ok).toBe(true);
  });

  it('edits and removes to-dos, and says which when a match is unclear', async () => {
    vi.mocked(db.todos.toArray).mockResolvedValue([
      { id: 't1', planId: 'p1', title: 'Book train to Kyoto', category: 'Booking', status: 'todo', autoGenerated: false, createdAt: '', updatedAt: '' },
      { id: 't2', planId: 'p1', title: 'Book train to Osaka', category: 'Booking', status: 'todo', autoGenerated: false, createdAt: '', updatedAt: '' },
    ]);
    const unclear = await executeAgentAction(plan(), { name: 'remove_todo', args: { titleMatch: 'book train' } });
    expect(unclear.ok).toBe(false);
    expect(unclear.message).toMatch(/More than one task/);
    await executeAgentAction(plan(), { name: 'remove_todo', args: { titleMatch: 'osaka' } });
    expect(db.todos.delete).toHaveBeenCalledWith('t2');
    await executeAgentAction(plan(), { name: 'edit_todo', args: { titleMatch: 'kyoto', dueDate: '2026-11-01' } });
    expect(db.todos.update).toHaveBeenCalledWith('t1', expect.objectContaining({ dueDate: '2026-11-01' }));
  });

  it('files a saved item under a day and an activity', async () => {
    vi.mocked(db.clipboard.toArray).mockResolvedValue([
      { id: 'c1', planId: 'p1', type: 'Hotel', title: 'Hotel Gracery booking', createdAt: '', updatedAt: '' },
    ]);
    const res = await executeAgentAction(plan(), {
      name: 'link_clipboard_item',
      args: { titleMatch: 'gracery', dayIndex: 1, activityRef: activityRef({ id: 'museum-1' }), time: '3pm' },
    });
    expect(res.ok).toBe(true);
    expect(db.clipboard.update).toHaveBeenCalledWith('c1', expect.objectContaining({ linkedDayIndex: 1, linkedActivityId: 'museum-1', time: '15:00' }));
  });
});

describe('what the chat is told about the trip', () => {
  const prompt = buildSystemPrompt(plan(), 'itinerary');

  it('shows each day with its date, and each activity with its ref and part of the day', () => {
    expect(prompt).toContain('Day 2 (dayIndex 1), Tue 10 Nov');
    expect(prompt).toContain(`[${activityRef({ id: 'museum-1' })}] Noon: Mori Art Museum`);
    expect(prompt).toContain('(nothing planned)');
  });

  it('explains swaps, parts of the day and duplicates', () => {
    expect(prompt).toMatch(/swap_activities once with both refs/);
    expect(prompt).toMatch(/morning \(5am–12pm\)/);
    expect(prompt).toMatch(/Never add something that is already in the trip/);
  });
});

