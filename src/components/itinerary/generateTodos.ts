import { v4 as uuidv4 } from 'uuid';
import { db, type Plan, type TodoItem } from '../../db';
import { travelBookingTitle, tripCountries } from '../../utils/travel';

/**
 * Auto-generate standard to-do items after itinerary generation.
 *
 * Rules (in order):
 *   1. If travel not booked → a task worded for how they are travelling:
 *      "Book train tickets to {destination}", and nothing at all for a road
 *      trip, which has no ticket to buy. It used to say "Book flights" for
 *      every trip regardless.
 *   2. If accommodation not booked → "Book accommodation for each night" (Booking)
 *   3. Entry requirements, per COUNTRY the trip touches, and only when the
 *      trip crosses a border:
 *        international false → nothing, whatever the visa answer says
 *        needsVisa true      → "Apply for visa to {country}" (Document)
 *        needsVisa null      → "Check visa requirements for {country}" (Document)
 *        needsVisa false     → nothing
 *      This used to fire unconditionally against the destination, so a Toronto
 *      trip produced "Apply for visa to Toronto" — wrong twice over: visas are
 *      a country-level rule, and the user may not need one at all. A domestic
 *      drive needed no visa task of any kind, and a trip through three
 *      countries needed three.
 *   4. If kids are travelling → "Check child entry requirements for {country}",
 *      on the same border-crossing condition.
 *
 * Deduplication: tasks are keyed by title.  If a task with the same title
 * already exists for this plan, it is silently skipped.  This means calling
 * autoGenerateTodos multiple times (e.g. after itinerary regeneration) is
 * fully safe.
 */
export async function autoGenerateTodos(plan: Plan): Promise<string[]> {
  const intake = plan.intake;
  if (!intake) return [];

  const existing = await db.todos.where('planId').equals(plan.id).toArray();
  const existingTitles = new Set(existing.map((t) => t.title));
  const toAdd: TodoItem[] = [];
  const now = new Date().toISOString();

  const maybeAdd = (item: Omit<TodoItem, 'id' | 'createdAt' | 'updatedAt'>) => {
    if (!existingTitles.has(item.title)) {
      toAdd.push({ ...item, id: uuidv4(), createdAt: now, updatedAt: now });
    }
  };

  // 1. Getting there — worded for the mode, and skipped entirely when there
  // is nothing to book.
  if (!intake.flightsBooked) {
    const title = travelBookingTitle(plan.arrival?.mode, plan.destination);
    if (title) {
      maybeAdd({
        planId: plan.id,
        title,
        category: 'Booking',
        status: 'todo',
        autoGenerated: true,
      });
    }
  }

  // 2. Accommodation
  if (!intake.accommodationBooked) {
    maybeAdd({
      planId: plan.id,
      title: 'Book accommodation for each night',
      category: 'Booking',
      status: 'todo',
      autoGenerated: true,
    });
  }

  /*
   * Entry rules are set by the country, not the city — "a Toronto visa" is
   * not a thing — and there are no entry rules at all on a trip that stays
   * inside one country. `international === false` is the user saying so.
   *
   * Every country the trip touches gets its own task, because a route through
   * three of them is three separate sets of rules.
   */
  const countries = tripCountries(plan);
  const entryPlaces = countries.length ? countries : [plan.destination];

  if (plan.international !== false) {
    for (const place of entryPlaces) {
      // 3. Visa — driven by the intake answer rather than assumed.
      if (intake.needsVisa === true) {
        maybeAdd({
          planId: plan.id,
          title: `Apply for visa to ${place}`,
          category: 'Document',
          status: 'todo',
          autoGenerated: true,
        });
      } else if (intake.needsVisa == null) {
        // Unsure, or never asked (a plan whose intake predates the question):
        // prompt a check rather than an application. `== null` covers both.
        maybeAdd({
          planId: plan.id,
          title: `Check visa requirements for ${place}`,
          category: 'Document',
          status: 'todo',
          autoGenerated: true,
        });
      }
      // needsVisa === false → nothing, which is the whole point of asking.

      // 4. Child entry requirements — also a country-level rule.
      if (intake.kids) {
        maybeAdd({
          planId: plan.id,
          title: `Check child entry requirements for ${place}`,
          category: 'Document',
          status: 'todo',
          autoGenerated: true,
        });
      }
    }
  }


  if (toAdd.length > 0) {
    await db.todos.bulkAdd(toAdd);
  }
  // Returned so a caller can name what it created. The intake used to build
  // its own copies of these tasks in order to do that, which is how the
  // "Book flights" wording and a city-scoped child-entry check survived here.
  return toAdd.map((t) => t.title);
}
