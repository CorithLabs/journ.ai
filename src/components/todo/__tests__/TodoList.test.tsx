import { describe, it, expect, vi, beforeEach } from 'vitest';
import { render, screen, fireEvent, waitFor } from '@testing-library/react';
import { MemoryRouter } from 'react-router-dom';
import TodoList from '../TodoList';
import { useLiveQuery } from 'dexie-react-hooks';
import { db } from '../../../db';

/** A row's actions live behind its "More actions" menu; open it first. */
const openMenu = (name: RegExp | string = /More actions for/, index = 0) =>
  fireEvent.click(screen.getAllByRole('button', { name: typeof name === 'string' ? `More actions for ${name}` : name })[index]);

vi.mock('dexie-react-hooks');

const today = new Date().toISOString().split('T')[0];
const yesterday = new Date(Date.now() - 86400000).toISOString().split('T')[0];
const tomorrow = new Date(Date.now() + 86400000).toISOString().split('T')[0];

const mockTodos = [
  {
    id: 'todo-1',
    planId: 'plan-1',
    title: 'Book flights to Tokyo',
    category: 'Booking',
    status: 'todo',
    autoGenerated: true,
    createdAt: new Date().toISOString(),
    updatedAt: new Date().toISOString(),
  },
  {
    id: 'todo-2',
    planId: 'plan-1',
    title: 'Pack rain jacket',
    category: 'Packing',
    status: 'done',
    autoGenerated: false,
    createdAt: new Date().toISOString(),
    updatedAt: new Date().toISOString(),
  },
];

const mockPinnedTodo = {
  id: 'todo-3',
  planId: 'plan-1',
  title: 'Tsukiji Market',
  category: 'Other',
  status: 'todo' as const,
  autoGenerated: false,
  sourceActivityId: 'act-1',
  sourceDayIndex: 0,
  createdAt: new Date().toISOString(),
  updatedAt: new Date().toISOString(),
};

describe('TodoList', () => {
  beforeEach(() => {
    vi.clearAllMocks();
  });

  // ── Add/Edit/Delete (Flow 10, Story 1) ──────────────────────────────────

  it('lists open tasks under To do, and folds done ones away', () => {
    vi.mocked(useLiveQuery).mockReturnValue(mockTodos);
    render(<MemoryRouter><TodoList planId="plan-1" /></MemoryRouter>);
    expect(screen.getByRole('region', { name: /to do/i })).toHaveTextContent('Book flights to Tokyo');
    expect(screen.queryByText('Pack rain jacket')).not.toBeInTheDocument();
    fireEvent.click(screen.getByTestId('done-toggle'));
    expect(screen.getByText('Pack rain jacket')).toBeInTheDocument();
  });

  // One list: the category headings split a short list into shorter ones.
  it('does not split the list by category', () => {
    vi.mocked(useLiveQuery).mockReturnValue(mockTodos);
    render(<MemoryRouter><TodoList planId="plan-1" /></MemoryRouter>);
    expect(screen.queryByRole('region', { name: /booking tasks/i })).not.toBeInTheDocument();
  });

  it('shows add form when clicking Add task', async () => {
    vi.mocked(useLiveQuery).mockReturnValue([]);
    render(<MemoryRouter><TodoList planId="plan-1" /></MemoryRouter>);
    fireEvent.click(screen.getByTestId('add-task-btn'));
    await waitFor(() => {
      expect(screen.getByTestId('add-task-form')).toBeInTheDocument();
    });
  });

  it('validates blank title on save', async () => {
    vi.mocked(useLiveQuery).mockReturnValue([]);
    render(<MemoryRouter><TodoList planId="plan-1" /></MemoryRouter>);
    fireEvent.click(screen.getByTestId('add-task-btn'));
    fireEvent.click(screen.getByTestId('save-task-btn'));
    await waitFor(() => {
      expect(screen.getByRole('alert')).toHaveTextContent('Title is required');
    });
  });

  it('saves a new task on valid submission', async () => {
    vi.mocked(useLiveQuery).mockReturnValue([]);
    vi.mocked(db.todos.add).mockResolvedValue('new-id');
    render(<MemoryRouter><TodoList planId="plan-1" /></MemoryRouter>);
    fireEvent.click(screen.getByTestId('add-task-btn'));
    fireEvent.change(screen.getByTestId('task-title-input'), {
      target: { value: 'Get travel insurance' },
    });
    fireEvent.click(screen.getByTestId('save-task-btn'));
    await waitFor(() => {
      expect(db.todos.add).toHaveBeenCalledWith(
        expect.objectContaining({ title: 'Get travel insurance', planId: 'plan-1' }),
      );
    });
  });

  /*
   * Tapping a title used to drop straight into editing it, which is a strange
   * answer to "what is this?" and was the only way to read a long one.
   */
  it('opens what the task knows when its title is tapped', async () => {
    vi.mocked(useLiveQuery).mockReturnValue([mockTodos[0]]);
    render(<MemoryRouter><TodoList planId="plan-1" /></MemoryRouter>);

    fireEvent.click(screen.getByText('Book flights to Tokyo'));

    await waitFor(() => expect(screen.getByTestId('task-detail')).toBeInTheDocument());
    expect(screen.queryByLabelText('Edit title')).not.toBeInTheDocument();
    expect(screen.getByTestId('detail-title')).toHaveTextContent('Book flights to Tokyo');
  });

  it('goes on to edit from the same modal, without closing it first', async () => {
    vi.mocked(useLiveQuery).mockReturnValue([mockTodos[0]]);
    render(<MemoryRouter><TodoList planId="plan-1" /></MemoryRouter>);
    fireEvent.click(screen.getByText('Book flights to Tokyo'));

    fireEvent.click(await screen.findByTestId('detail-edit'));

    expect(await screen.findByLabelText('Edit title')).toBeInTheDocument();
  });

  it('reaches the editor directly from the pencil', async () => {
    vi.mocked(useLiveQuery).mockReturnValue([mockTodos[0]]);
    render(<MemoryRouter><TodoList planId="plan-1" /></MemoryRouter>);

    openMenu();
    fireEvent.click(screen.getByTestId('task-edit'));

    expect(await screen.findByLabelText('Edit title')).toBeInTheDocument();
  });

  /*
   * Saving on blur meant the only way to find out whether an edit had taken
   * was to look. The editor now ends in a Save, the way the itinerary and
   * clipboard editors do.
   */
  it('saving an updated title calls db.todos.update', async () => {
    vi.mocked(useLiveQuery).mockReturnValue([mockTodos[0]]);
    render(<MemoryRouter><TodoList planId="plan-1" /></MemoryRouter>);
    openMenu();
    fireEvent.click(screen.getByTestId('task-edit'));
    const editInput = await screen.findByLabelText('Edit title');
    fireEvent.change(editInput, { target: { value: 'Book flights to Osaka' } });
    fireEvent.click(screen.getByTestId('task-save-btn'));
    await waitFor(() => {
      expect(db.todos.update).toHaveBeenCalledWith(
        'todo-1',
        expect.objectContaining({ title: 'Book flights to Osaka' }),
      );
    });
  });

  it('delete: shows undo toast after deleting a task', async () => {
    vi.mocked(useLiveQuery).mockReturnValue([mockTodos[0]]);
    vi.mocked(db.todos.delete).mockResolvedValue(undefined);
    render(<MemoryRouter><TodoList planId="plan-1" /></MemoryRouter>);
    openMenu(/More actions for Book flights/i);
    const delBtn = screen.getByLabelText(/delete: book flights/i);
    fireEvent.click(delBtn);
    await waitFor(() => {
      expect(db.todos.delete).toHaveBeenCalledWith('todo-1');
      expect(screen.getByText('Task deleted')).toBeInTheDocument();
    });
  });

  it('delete: undo restores the task via db.todos.add', async () => {
    vi.mocked(useLiveQuery).mockReturnValue([mockTodos[0]]);
    vi.mocked(db.todos.delete).mockResolvedValue(undefined);
    vi.mocked(db.todos.add).mockResolvedValue('todo-1');
    render(<MemoryRouter><TodoList planId="plan-1" /></MemoryRouter>);
    openMenu(/More actions for Book flights/i);
    const delBtn = screen.getByLabelText(/delete: book flights/i);
    fireEvent.click(delBtn);
    const undoBtn = await screen.findByText('Undo');
    fireEvent.click(undoBtn);
    await waitFor(() => {
      expect(db.todos.add).toHaveBeenCalledWith(
        expect.objectContaining({ id: 'todo-1', title: 'Book flights to Tokyo' }),
      );
    });
  });

  it('shows past-due date with warning colour class', () => {
    const pastTodo = { ...mockTodos[0], dueDate: yesterday };
    vi.mocked(useLiveQuery).mockReturnValue([pastTodo]);
    render(<MemoryRouter><TodoList planId="plan-1" /></MemoryRouter>);
    // The "Past" label should appear next to the date input in the form area
    // In the task row, the due date span should carry warning styling
    expect(screen.getByText(`Due ${yesterday}`)).toBeInTheDocument();
  });

  it('shows loading spinner when todos undefined', () => {
    vi.mocked(useLiveQuery).mockReturnValue(undefined);
    render(<MemoryRouter><TodoList planId="plan-1" /></MemoryRouter>);
    expect(screen.getByLabelText('Loading')).toBeInTheDocument();
  });

  // ── Progress / Complete (Flow 10, Story 2) ──────────────────────────────

  it('counts what is left to do, and what is done', () => {
    vi.mocked(useLiveQuery).mockReturnValue(mockTodos);
    render(<MemoryRouter><TodoList planId="plan-1" /></MemoryRouter>);
    expect(screen.getByRole('heading', { name: /to do/i })).toHaveTextContent('1');
    expect(screen.getByTestId('done-toggle')).toHaveTextContent('Done (1)');
  });

  it('hides progress bar when no tasks', () => {
    vi.mocked(useLiveQuery).mockReturnValue([]);
    render(<MemoryRouter><TodoList planId="plan-1" /></MemoryRouter>);
    expect(screen.queryByRole('progressbar')).not.toBeInTheDocument();
  });

  it('shows celebration when all done', () => {
    const allDone = mockTodos.map((t) => ({ ...t, status: 'done' }));
    vi.mocked(useLiveQuery).mockReturnValue(allDone);
    render(<MemoryRouter><TodoList planId="plan-1" /></MemoryRouter>);
    expect(screen.getByTestId('to-sort-empty')).toHaveTextContent('All done.');
  });

  it('toggles task status on checkbox click', async () => {
    vi.mocked(useLiveQuery).mockReturnValue([mockTodos[0]]);
    render(<MemoryRouter><TodoList planId="plan-1" /></MemoryRouter>);
    const checkbox = screen.getByLabelText('Mark complete');
    fireEvent.click(checkbox);
    await waitFor(() => {
      expect(db.todos.update).toHaveBeenCalledWith(
        'todo-1',
        expect.objectContaining({ status: 'done' }),
      );
    });
  });

  it('toggles a done task back to todo on checkbox click', async () => {
    vi.mocked(useLiveQuery).mockReturnValue([mockTodos[1]]);
    render(<MemoryRouter><TodoList planId="plan-1" /></MemoryRouter>);
    fireEvent.click(screen.getByTestId('done-toggle'));
    const checkbox = screen.getByLabelText('Mark incomplete');
    fireEvent.click(checkbox);
    await waitFor(() => {
      expect(db.todos.update).toHaveBeenCalledWith(
        'todo-2',
        expect.objectContaining({ status: 'todo' }),
      );
    });
  });

  it('completed tasks appear with line-through text', () => {
    vi.mocked(useLiveQuery).mockReturnValue([mockTodos[1]]); // status: done
    render(<MemoryRouter><TodoList planId="plan-1" /></MemoryRouter>);
    fireEvent.click(screen.getByTestId('done-toggle'));
    const titleBtn = screen.getByText('Pack rain jacket');
    expect(titleBtn.className).toContain('line-through');
  });

  // ── Generated badge ──────────────────────────────────────────────────────

  // A badge on most rows said nothing about any one of them.
  it('does not badge auto-generated tasks in the list', () => {
    vi.mocked(useLiveQuery).mockReturnValue([mockTodos[0]]);
    render(<MemoryRouter><TodoList planId="plan-1" /></MemoryRouter>);
    expect(screen.queryByText('Generated')).not.toBeInTheDocument();
  });

  // ── Travel basics ────────────────────────────────────────────────────────

  // For trips made before new ones came with them.
  it('offers the travel basics to a trip that has none, and adds them', async () => {
    vi.mocked(useLiveQuery).mockReturnValue([mockTodos[0]]);
    render(<MemoryRouter><TodoList planId="plan-1" /></MemoryRouter>);
    fireEvent.click(screen.getByTestId('add-travel-basics'));
    await waitFor(() => expect(db.todos.bulkAdd).toHaveBeenCalled());
    const added = vi.mocked(db.todos.bulkAdd).mock.calls[0][0] as Array<{ title: string; planId: string }>;
    expect(added.map((t) => t.title)).toContain('Pack a universal plug adapter');
    expect(added.every((t) => t.planId === 'plan-1')).toBe(true);
  });

  // Deleting one on purpose must not bring the offer back.
  it('does not offer them once the trip has any', () => {
    vi.mocked(useLiveQuery).mockReturnValue([{ ...mockTodos[0], id: 'b', title: 'Pack headache medicine' }]);
    render(<MemoryRouter><TodoList planId="plan-1" /></MemoryRouter>);
    expect(screen.queryByTestId('add-travel-basics')).not.toBeInTheDocument();
  });

  // ── Attach proof ─────────────────────────────────────────────────────────

  // Most tasks are finished by getting something: saving it ticks the task.
  it('saves the proof for a task and ticks it off', async () => {
    vi.mocked(useLiveQuery).mockReturnValue([mockTodos[0]]);
    render(<MemoryRouter><TodoList planId="plan-1" /></MemoryRouter>);
    fireEvent.click(screen.getByRole('button', { name: 'More actions for Book flights to Tokyo' }));
    fireEvent.click(screen.getByTestId('task-attach'));
    // Named after the task, without the "Book".
    expect(screen.getByTestId('title-input')).toHaveValue('flights to Tokyo');
    fireEvent.click(screen.getByTestId('save-item-btn'));
    await waitFor(() => expect(db.clipboard.add).toHaveBeenCalledWith(expect.objectContaining({ title: 'flights to Tokyo', planId: 'plan-1' })));
    await waitFor(() => expect(db.todos.update).toHaveBeenCalledWith('todo-1', expect.objectContaining({ status: 'done' })));
    expect(await screen.findByText('Saved, and ticked off')).toBeInTheDocument();
  });

  it('does not offer to attach proof to a task already done', () => {
    vi.mocked(useLiveQuery).mockReturnValue([mockTodos[1]]);
    render(<MemoryRouter><TodoList planId="plan-1" /></MemoryRouter>);
    fireEvent.click(screen.getByTestId('done-toggle'));
    fireEvent.click(screen.getByRole('button', { name: 'More actions for Pack rain jacket' }));
    expect(screen.queryByTestId('task-attach')).not.toBeInTheDocument();
  });

  // ── Pin from itinerary (Flow 11) ─────────────────────────────────────────

  it('shows From itinerary badge on pinned tasks with day label', () => {
    vi.mocked(useLiveQuery).mockReturnValue([mockPinnedTodo]);
    render(<MemoryRouter><TodoList planId="plan-1" /></MemoryRouter>);
    expect(screen.getByText(/From itinerary.*Day 1/)).toBeInTheDocument();
  });
});
