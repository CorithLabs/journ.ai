interface Props { planId: string; }

const CATS = ['Booking', 'Document', 'Packing', 'Other'] as const;
type Cat = (typeof CATS)[number];

const CAT_COLOR: Record<Cat, string> = {
  Booking: 'border-l-category-cyan',
  Document: 'border-l-category-sky',
  Packing: 'border-l-category-emerald',
  Other: 'border-l-category-slate',
};

function AddForm({ planId, onDone }: { planId: string; onDone: () => void }) {
  const isMobile = useIsMobile();
  const [title, setTitle] = useState('');
  const [due, setDue] = useState('');
  const [cat, setCat] = useState<Cat>('Other');
  const [err, setErr] = useState('');
  const [saving, setSaving] = useState(false);
  const today = new Date().toISOString().split('T')[0];

  const submit = async (e: React.FormEvent) => {
    e.preventDefault();
    if (!title.trim()) { setErr('Title is required'); return; }
    setSaving(true);
    try {
      const now = new Date().toISOString();
      await db.todos.add({ id: uuidv4(), planId, title: title.trim(), category: cat, status: 'todo', dueDate: due || undefined, autoGenerated: false, createdAt: now, updatedAt: now });
      setTitle(''); setDue(''); setCat('Other'); onDone();
    } finally { setSaving(false); }
  };

  /*
   * Was a form that unfolded inside the list, ending in a full-width "Add
   * Task" slab and offering no way out but pressing the trigger again. Adding
   * a task is the same job as adding an activity, so it is the same dialog.
   */
  return (
    <Modal title="Add task" onClose={onDone} anchor={isMobile ? 'top' : 'center'}>
    <form onSubmit={submit} className="space-y-3" data-testid="add-task-form">
      <div>
        <input value={title} onChange={e => { setTitle(e.target.value); setErr(''); }} placeholder="Task title"
          className={fieldClass}
          data-testid="task-title-input" aria-label="Task title" />
        {err && <p role="alert" className="mt-1 text-xs text-status-danger">{err}</p>}
      </div>
      <div className="flex gap-2">
        {/* A date and a category are both short. Paired on one row rather
            than stacked, which is what the extra width is for. */}
        <input type="date" value={due} onChange={e => setDue(e.target.value)}
          className={`flex-1 ${fieldClassAuto} ${due && due < today ? '!border-status-warning/50' : ''}`}
          aria-label="Due date" />
        {due && due < today && <p className="text-xs text-status-warning self-center">Past</p>}
        <select value={cat} onChange={e => setCat(e.target.value as Cat)} aria-label="Category"
          className={fieldClassAuto}>
          {CATS.map(c => <option key={c} value={c}>{c}</option>)}
        </select>
      </div>
      <div className="flex gap-2 pt-1">
        <Button type="submit" disabled={saving} data-testid="save-task-btn">
          {saving ? 'Saving…' : 'Save'}
        </Button>
        <Button variant="secondary" onClick={onDone} data-testid="cancel-task-btn">Cancel</Button>
      </div>
    </form>
    </Modal>
  );
}

interface RowProps {
  item: TodoItem;
  plan: Plan | undefined;
  onToggle: () => void;
  onDel: () => void;
  onUpd: (t: string) => void;
  onPin: () => void;
  onAttach: () => void;
  onNavigateToDay: (dayIndex: number) => void;
}

function Row({ item, plan, onToggle, onDel, onUpd, onPin, onAttach, onNavigateToDay }: RowProps) {
  /**
   * Closed, reading the task, or changing it. The same two modes the itinerary
   * cards use, so a card behaves the same wherever it is.
   */
  const [detail, setDetail] = useState<null | 'view' | 'edit'>(null);
  const [val, setVal] = useState(item.title);
  const ref = useRef<HTMLInputElement>(null);

  const commit = () => {
    if (val.trim()) onUpd(val.trim());
    else setVal(item.title);
    setDetail(null);
  };
  const cancel = () => {
    setVal(item.title);
    setDetail(null);
  };
  const today = new Date().toISOString().split('T')[0];
  const pastDue = item.dueDate && item.dueDate < today && item.status !== 'done';
  const color = CAT_COLOR[item.category as Cat] ?? CAT_COLOR.Other;

  // Determine if the pinned source activity still exists
  const sourceExists = item.sourceActivityId
    ? plan?.itinerary?.some(day =>
        day.activities.some(act => act.id === item.sourceActivityId)
      ) ?? null // null = plan not yet loaded, show badge normally
    : null;

  const handleBadgeClick = () => {
    if (item.sourceDayIndex !== undefined) {
      onNavigateToDay(item.sourceDayIndex);
    }
  };

  return (
    // Not overflow-hidden: that would clip the actions menu. The row's blur
    // makes it a stacking context, so while its menu is open it is lifted over
    // the rows below.
    <div className={`card-surface group relative has-[[aria-expanded=true]]:z-20 flex items-stretch rounded-card border-l-2 ${color}`} data-testid="task-row">
      <div className="flex-1 min-w-0 flex items-center gap-3 py-2.5 px-3">
      <button onClick={onToggle} className="shrink-0 text-ink-muted hover:text-accent" aria-label={item.status === 'done' ? 'Mark incomplete' : 'Mark complete'}>
        {item.status === 'done' ? <CheckSquare size={18} className="text-status-success" /> : <Square size={18} />}
      </button>
      <div className="flex-1 min-w-0">
        <div>
              {/* Opens what the task knows rather than an edit box. Tapping a
                  title used to drop straight into editing it, which is a
                  strange answer to "what is this?" and the only way to read a
                  long one. */}
              <button
                onClick={() => setDetail('view')}
                className={`text-sm text-left w-full ${item.status === 'done' ? 'line-through text-ink-muted' : 'text-ink-primary'}`}
                aria-label={`${item.title} — open details`}
                data-testid="task-title"
              >{item.title}</button>
              <div className="flex items-center gap-2 mt-0.5 flex-wrap">
                {item.pinned && <span className="text-xs font-semibold text-accent bg-accent/10 px-2 py-0.5 rounded-full" data-testid="task-pinned-flag">Pinned</span>}
                {item.sourceActivityId && (
                  sourceExists === false
                    ? <span className="text-xs text-ink-muted bg-surface-overlay px-2 py-0.5 rounded-full">📍 Source removed</span>
                    : <button
                        onClick={handleBadgeClick}
                        className="text-xs text-ink-muted bg-surface-overlay px-2 py-0.5 rounded-full hover:bg-surface-raised transition-colors"
                        aria-label={`Go to Day ${(item.sourceDayIndex ?? 0) + 1} in itinerary`}
                        data-testid="itinerary-badge"
                      >
                        📍 From itinerary{item.sourceDayIndex !== undefined ? ` · Day ${item.sourceDayIndex + 1}` : ''}
                      </button>
                )}
                {item.dueDate && <span className={`text-xs ${pastDue ? 'text-status-warning' : 'text-ink-muted'}`}>Due {item.dueDate}</span>}
              </div>
        </div>
      </div>
      </div>

      {/* One menu instead of a rail of three icons with a red bin on every
          task. The pinned state still shows on the task itself. */}
      <div className="shrink-0 self-center pr-1" data-testid="task-actions">
        <ActionMenu
          label={`More actions for ${item.title}`}
          menuLabel={`Actions for ${item.title}`}
          items={[
            // The booking email, the ticket: saving the proof is what finishes
            // most of these, so it ticks the task off as it saves.
            ...(item.status !== 'done' ? [{ label: 'Attach proof', ariaLabel: `Attach proof: ${item.title}`, icon: <Paperclip size={15} />, onSelect: onAttach, testId: 'task-attach' }] : []),
            { label: item.pinned ? 'Unpin' : 'Pin to top', ariaLabel: item.pinned ? `Unpin: ${item.title}` : `Pin to top: ${item.title}`, icon: <Pin size={15} />, onSelect: onPin, testId: 'task-pin' },
            { label: 'Edit', ariaLabel: `Edit: ${item.title}`, icon: <Pencil size={15} />, onSelect: () => setDetail('edit'), testId: 'task-edit' },
            { label: 'Delete', ariaLabel: `Delete: ${item.title}`, icon: <Trash2 size={15} />, onSelect: onDel, danger: true, testId: 'task-delete' },
          ]}
        />
      </div>

      {detail && (
        <DetailModal
          title={detail === 'edit' ? 'Edit task' : 'Task'}
          onClose={cancel}
          onEdit={() => setDetail('edit')}
          onDelete={() => { setDetail(null); onDel(); }}
          deleteLabel={`Delete: ${item.title}`}
          // A task has no place of its own, but one raised from an activity
          // has a day — which is the equivalent move, and the badge that
          // offered it was easy to miss among the others.
          goTo={item.sourceDayIndex !== undefined && sourceExists !== false
            ? { label: `Day ${item.sourceDayIndex + 1}`, onClick: () => { setDetail(null); onNavigateToDay(item.sourceDayIndex!); } }
            : null}
          testId="task-detail"
        >
          {detail === 'edit' ? (
            <div className="space-y-2" data-testid="task-edit-form">
              {/* Saving silently on blur meant the only way to find out whether
                  an edit had taken was to look. Now it says so, in the same
                  words the other two editors use. */}
              <input ref={ref} value={val} onChange={e => setVal(e.target.value)}
                onKeyDown={e => { if (e.key === 'Enter') commit(); if (e.key === 'Escape') cancel(); }}
                className={fieldClass}
                aria-label="Edit title" autoFocus />
              <div className="flex gap-2 pt-1">
                <Button size="sm" onClick={commit} data-testid="task-save-btn">Save</Button>
                <Button size="sm" variant="secondary" onClick={cancel} data-testid="task-cancel-btn">Cancel</Button>
              </div>
            </div>
          ) : (
            <dl className="-mt-1">
              <DetailRow label="Task" testId="detail-title">{item.title}</DetailRow>
              <DetailRow label="Category">{item.category}</DetailRow>
              <DetailRow label="Status">
                {item.status === 'done' ? 'Complete' : 'Not done'}
              </DetailRow>
              {item.dueDate && (
                <DetailRow label="Due">
                  <span className={pastDue ? 'text-status-warning' : undefined}>
                    {item.dueDate}{pastDue ? ' — past due' : ''}
                  </span>
                </DetailRow>
              )}
              {item.sourceActivityId && (
                <DetailRow label="From">
                  {sourceExists === false
                    ? <span className="text-ink-muted">An activity that has since been removed</span>
                    : `The itinerary${item.sourceDayIndex !== undefined ? `, day ${item.sourceDayIndex + 1}` : ''}`}
                </DetailRow>
              )}
              {(item.pinned || item.autoGenerated) && (
                <DetailRow label="Flags">
                  <span className="flex flex-wrap items-center gap-2">
                    {item.pinned && (
                      <span className="text-xs text-accent bg-accent/10 px-2 py-0.5 rounded-full">Pinned</span>
                    )}
                    {item.autoGenerated && (
                      <span className="text-xs text-accent bg-accent/10 px-2 py-0.5 rounded-full">
                        Added for you
                      </span>
                    )}
                  </span>
                </DetailRow>
              )}
            </dl>
          )}
        </DetailModal>
      )}
    </div>
  );
}

/**
 * Essentials' "To do": what still needs doing for the trip.
 *
 * Was its own tab, grouped by category under a progress bar. Most of these
 * are finished by getting something — the booking, the ticket — and that
 * thing lived in another tab, the Clipboard. They are one tab now: this list
 * on top, what is kept below, and "Attach proof" moves a task from one to the
 * other.
 */
export default function TodoList({ planId }: Props) {
  const [showAdd, setShowAdd] = useState(false);
  const [showDone, setShowDone] = useState(false);
  const [attaching, setAttaching] = useState<TodoItem | null>(null);
  const [toast, setToast] = useState<{ msg: string; undo?: () => void } | null>(null);
  const navigate = useNavigate();
  const todos = useLiveQuery(() => db.todos.where('planId').equals(planId).sortBy('createdAt'), [planId]);
  const plan = useLiveQuery(() => db.plans.get(planId), [planId]);

  if (todos === undefined) return (
    <div className="flex items-center justify-center py-8">
      <div className="w-8 h-8 border-2 border-accent border-t-transparent rounded-full animate-spin" aria-label="Loading" />
    </div>
  );

  const stamp = () => new Date().toISOString();
  const pin = (item: TodoItem) => db.todos.update(item.id, { pinned: !item.pinned, updatedAt: stamp() });
  const toggle = (item: TodoItem) =>
    db.todos.update(item.id, { status: item.status === 'done' ? 'todo' : 'done', updatedAt: stamp() });
  const del = async (item: TodoItem) => {
    await db.todos.delete(item.id);
    setToast({ msg: 'Task deleted', undo: async () => { await db.todos.add(item); setToast(null); } });
  };
  const upd = (item: TodoItem, title: string) => db.todos.update(item.id, { title, updatedAt: stamp() });

  const navigateToDay = (dayIndex: number) => {
    navigate(`/plan/${planId}/itinerary`);
    // Scroll happens after navigation; use a short timeout to allow the DOM to update
    setTimeout(() => {
      document.getElementById(`day-${dayIndex}`)?.scrollIntoView({ behavior: scrollBehavior() });
    }, 150);
  };

  const basics = travelBasics(planId, plan?.international, {
    destination: plan?.countryCode ?? plan?.country,
    origin: plan?.origin?.countryCode ?? plan?.origin?.country,
  });
  const addBasics = async () => {
    const now = stamp();
    await db.todos.bulkAdd(basics.map((b) => ({ ...b, id: uuidv4(), createdAt: now, updatedAt: now })));
  };

  // Pinned first: the one or two that matter, in a list the app also adds to.
  const open = todos.filter((t) => t.status !== 'done').sort((a, b) => Number(!!b.pinned) - Number(!!a.pinned));
  const done = todos.filter((t) => t.status === 'done');

  const row = (item: TodoItem) => (
    <Row key={item.id} item={item} plan={plan} onToggle={() => toggle(item)} onDel={() => del(item)}
      onUpd={(t) => upd(item, t)} onPin={() => pin(item)} onAttach={() => setAttaching(item)} onNavigateToDay={navigateToDay} />
  );

  return (
    <section aria-labelledby="to-sort" data-testid="todo-list">
      <SectionHead id="to-sort" title="To do" count={open.length} addLabel="Add task" onAdd={() => setShowAdd(true)} addTestId="add-task-btn" />

      {open.length === 0 && (
        <p className="py-3 text-sm text-ink-muted" data-testid="to-sort-empty">
          {done.length > 0 ? 'All done.' : 'Nothing to do yet.'}
        </p>
      )}
      <div className="space-y-1.5">{open.map(row)}</div>

      {/* For trips made before new ones came with these. Offered only while the
          trip has none of them, so deleting one on purpose does not bring the
          offer back. */}
      {basics.length > 0 && basics.every((b) => !todos.some((t) => t.title === b.title)) && (
        <button
          type="button"
          onClick={addBasics}
          className="mt-2 min-h-11 flex items-center gap-1.5 text-sm text-accent hover:underline"
          data-testid="add-travel-basics"
        >
          + Add travel basics <span className="text-ink-muted">(plug adapter, eSIM, headache medicine, power bank)</span>
        </button>
      )}

      {done.length > 0 && (
        <div className="mt-2">
          <button
            type="button"
            onClick={() => setShowDone((v) => !v)}
            aria-expanded={showDone}
            className="h-11 flex items-center gap-1.5 text-sm text-ink-muted hover:text-ink-primary"
            data-testid="done-toggle"
          >
            <ChevronDown size={15} className={`transition-transform ${showDone ? 'rotate-180' : ''}`} aria-hidden="true" />
            Done ({done.length})
          </button>
          {showDone && <div className="space-y-1.5">{done.map(row)}</div>}
        </div>
      )}

      {showAdd && <AddForm planId={planId} onDone={() => setShowAdd(false)} />}
      {attaching && (
        <AddItemDrawer
          planId={planId}
          initialTitle={attaching.title.replace(/^book\s+/i, '')}
          onClose={() => setAttaching(null)}
          onSaved={async () => {
            await db.todos.update(attaching.id, { status: 'done', updatedAt: stamp() });
            setToast({ msg: 'Saved, and ticked off' });
            setAttaching(null);
          }}
        />
      )}
      {toast && <Toast message={toast.msg} onDismiss={() => setToast(null)} action={toast.undo ? { label: 'Undo', onClick: toast.undo } : undefined} />}
    </section>
  );
}
